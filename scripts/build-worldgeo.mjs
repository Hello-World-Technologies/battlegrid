// Turns data/geo/world.json (every country as a coarse outline, Mercator map units: 1 unit = 1 degree of longitude,
// x east, y south) into src/game/core/worldgeo.ts, the compact list the game lays its levels over.
//   node scripts/build-worldgeo.mjs
// Each entry is [iso, labelX, labelY, rings]; rings is a list of flat [x0, y0, x1, y1, ...] outlines (mainland and islands).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const world = JSON.parse(readFileSync(join(root, 'data', 'geo', 'world.json'), 'utf8'));

const ringArea = (r) => {
  let a = 0;
  for (let i = 0; i < r.length; i += 2) {
    const j = (i + 2) % r.length;
    a += r[i] * r[j + 1] - r[j] * r[i + 1];
  }
  return Math.abs(a) / 2;
};

const out = [];
for (const c of world.countries) {
  if (c.iso === 'ATA') continue; // the southern ice cap is not a place to fight
  const rings = [];
  for (const sub of c.d.split('M').filter(Boolean)) {
    const pts = [...sub.matchAll(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g)].map((m) => [Number(m[1]), Number(m[2])]);
    // Drop repeated points, then rings too small to see.
    const flat = [];
    for (const [x, y] of pts) {
      const n = flat.length;
      if (n && flat[n - 2] === x && flat[n - 1] === y) continue;
      flat.push(x, y);
    }
    if (flat.length >= 6 && ringArea(flat) > 0.02) rings.push(flat);
  }
  if (rings.length) out.push([c.iso, c.x, c.y, rings]);
}

const json = JSON.stringify(out);
const src = `// src/game/core/worldgeo.ts
//
// GENERATED by scripts/build-worldgeo.mjs from data/geo/world.json. Do not edit.
// Every country as [iso, labelX, labelY, rings] in Mercator map units (1 unit = 1 degree of longitude, x east, y south);
// rings are flat [x0, y0, x1, y1, ...] outlines (mainland and islands). Parsed once, on first use.

export const WORLD_GEO_JSON = ${JSON.stringify(json)};
`;
writeFileSync(join(root, 'src', 'game', 'core', 'worldgeo.ts'), src);
console.log(`${out.length} countries, ${(src.length / 1024).toFixed(0)} KB`);
